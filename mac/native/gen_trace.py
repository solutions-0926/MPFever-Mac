"""Generates probe4.c: counting hooks on EVERY function of a range of the game (default: the CommandList.cpp unit), to find
which of them a given action calls (for example: which function the interface's build tools call to add a command).

    python3 gen_trace.py <path to TransportFever3> <first address> <last address> > probe4.c

Only functions whose first four instructions are position independent are hooked (the others are listed on stderr). The module
logs, every time the file ~/mpf-mark appears (the player makes it with `touch ~/mpf-mark`; the module deletes it), the functions
called since the last mark: how often, how many of the calls came from the main thread, and one caller. Mark, do one action in
the game (build one road), mark again: the functions in the second block are the ones that action calls."""
import struct
import sys

import capstone
import lief

path, lo, hi = sys.argv[1], int(sys.argv[2], 16), int(sys.argv[3], 16)
b = lief.MachO.parse(path).at(0)
data = open(path, "rb").read()
t = b.get_section("__text")
base = t.virtual_address
md = capstone.Cs(capstone.CS_ARCH_ARM64, capstone.CS_MODE_ARM)


def word(a):
    o = t.offset + a - base
    return struct.unpack("<I", data[o:o + 4])[0]


def ins(a, n):
    o = t.offset + a - base
    return list(md.disasm(data[o:o + 4 * n], a))


PI = {"stp", "sub", "add", "mov", "str", "stur", "ldr", "ldp", "ldur", "orr", "movz", "movk", "sturb", "strb", "strh", "stur", "sxtw", "and", "eor", "cmp", "nop", "ldrb", "ldrh", "movi", "stp"}
starts = []
for a in range(lo, hi, 4):
    x, p = word(a), word(a - 4)
    prev_end = p == 0xD65F03C0 or (p & 0xFC000000) == 0x14000000 or (p & 0xFFE0001F) == 0xD4200000 or (p & 0xFC000000) == 0x94000000
    if prev_end and ((x & 0xFF0003FF) == 0xD10003FF or (x & 0xFFC00000) == 0xA9800000):
        starts.append(a)
hooks, skipped = [], []
for a in starts:
    i4 = ins(a, 4)
    ok = len(i4) == 4 and all(i.mnemonic in PI and "pc" not in i.op_str for i in i4)
    # no stolen instruction may read x16/x17 (the thunk uses them)
    ok = ok and all("x16" not in i.op_str and "x17" not in i.op_str and "w16" not in i.op_str and "w17" not in i.op_str for i in i4)
    (hooks if ok else skipped).append(a)
sys.stderr.write("functions %d, hooked %d, skipped %d: %s\n" % (len(starts), len(hooks), len(skipped), " ".join(hex(a) for a in skipped)))
n = len(hooks)
out = []
w = out.append
w("// GENERATED by gen_trace.py: do not edit. Probe 4: counting hooks on %d functions of the game (0x%x..0x%x); mark with `touch ~/mpf-mark`." % (n, lo, hi))
w(open("probe3_head.c").read())
w("extern int unlink(const char*);\nextern int access(const char*, int);")
w("#define NHOOKS %d" % n)
w("static const u64 HADDR[NHOOKS] = {" + ",".join("0x%xUL" % a for a in hooks) + "};")
w("static const u32 HWORDS[NHOOKS][4] = {" + ",".join("{" + ",".join("0x%08x" % word(a + 4 * k) for k in range(4)) + "}" for a in hooks) + "};")
w("u64 hook_resume[NHOOKS];\nvolatile u32 hook_calls[NHOOKS];\nvolatile u32 hook_main[NHOOKS];\nu64 hook_lr[NHOOKS];\nu64 main_tls;")
lines = [".text", ".p2align 2"]
for i, a in enumerate(hooks):
    lines.append(".globl _th%d\n_th%d:" % (i, i))
    # (only x16/x17 are used, and x30 is not touched: a thunk runs on any thread, at any moment)
    lines.append("  mrs x17, tpidrro_el0")
    lines.append("  adrp x16, _main_tls@PAGE\n  ldr x16, [x16, _main_tls@PAGEOFF]\n  cmp x16, x17\n  cset w17, eq")
    lines.append("  adrp x16, _hook_main@PAGE\n  add x16, x16, _hook_main@PAGEOFF+%d\n  stadd w17, [x16]" % (i * 4))
    lines.append("  adrp x16, _hook_lr@PAGE\n  add x16, x16, _hook_lr@PAGEOFF+%d\n  str x30, [x16]" % (i * 8))
    lines.append("  adrp x16, _hook_calls@PAGE\n  add x16, x16, _hook_calls@PAGEOFF+%d\n  mov w17, #1\n  stadd w17, [x16]" % (i * 4))
    for ii in ins(a, 4):
        lines.append("  %s %s" % (ii.mnemonic, ii.op_str))
    lines.append("  adrp x16, _hook_resume@PAGE\n  ldr x16, [x16, _hook_resume@PAGEOFF+%d]\n  br x16" % (i * 8))
w("__asm__(" + "\n    ".join('"%s\\n"' % l.replace("\n", "\\n") for l in lines) + ");")
for i in range(n):
    w("extern void th%d(void);" % i)
w("static void* const THUNK[NHOOKS] = {" + ",".join("(void*)&th%d" % i for i in range(n)) + "};")
w(open("probe4_tail.c").read())
print("\n".join(out))
