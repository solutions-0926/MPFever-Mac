"""Generates probe3.c: counting hooks on functions of the Mac build of Transport Fever 3, from its TransportFever3 file.

    python3 gen_hooks.py <path to TransportFever3> > probe3.c

Each hook is a 16-byte jump written over the first four instructions of a function (they must be position independent: stp,
sub sp...), a thunk that counts the call, keeps the first two arguments, runs the four instructions it displaced and goes on.
The four instructions are copied from the file here, so a thunk belongs to one game build; at run time the bytes at the place
are compared with them first, and nothing is written when they differ."""
import struct
import sys

import capstone
import lief

HOOKS = [  # name, file address of the function (before the slide)
    ("apply",      0x100a6fa34),   # "Simulation Thread: Apply Command"
    ("wbp_a",      0x100a77b2c),   # refers to "WorldBuildProposal"
    ("wbp_b",      0x10170912c),   # refers to "WorldBuildProposal"
    ("replicate",  0x100113524),   # refers to "Replicate"
    ("makewbp",    0x100f28020),   # refers to "makeWorldBuildProposalCmd"
    ("simthread",  0x1000cbb50),   # refers to "Simulation Thread" (the thread's name)
]
SEED = (0x103f833fc, 0x52800401, 0x94000112, 0xb9012260)   # address, word before, the bl, word after

path = sys.argv[1]
b = lief.MachO.parse(path).at(0)
data = open(path, "rb").read()
t = b.get_section("__text")
md = capstone.Cs(capstone.CS_ARCH_ARM64, capstone.CS_MODE_ARM)


def words(addr, n):
    o = t.offset + addr - t.virtual_address
    return list(struct.unpack("<%dI" % n, data[o:o + 4 * n]))


def asm(addr, n):
    o = t.offset + addr - t.virtual_address
    return [(i.mnemonic, i.op_str) for i in md.disasm(data[o:o + 4 * n], addr)]


ok_mn = {"stp", "sub", "mov", "str", "add"}
out = []
w = out.append
w("// GENERATED by gen_hooks.py from the game's TransportFever3 file: do not edit. Probe 3: count the calls of six functions and write")
w("// a line every half second when something changed. Also patches the Lua seed (as probe 2). Log: $HOME/mpfever-probe3.log")
w("// Freestanding: cross-built by build-probe.sh.")
w(open("probe3_head.c").read())
n = len(HOOKS)
w("#define NHOOKS %d" % n)
w("static const char* const HNAME[NHOOKS] = { " + ", ".join('"%s"' % h[0] for h in HOOKS) + " };")
w("static const u64 HADDR[NHOOKS] = { " + ", ".join("0x%xUL" % h[1] for h in HOOKS) + " };")
w("static const u32 HWORDS[NHOOKS][4] = {")
asm_blocks = []
for name, a in HOOKS:
    ws = words(a, 4)
    ins = asm(a, 4)
    for m, _ in ins:
        if m not in ok_mn:
            sys.exit("%s: instruction %s is not position independent" % (name, m))
    for (m, o) in ins:
        if m in ("add", "mov") and "pc" in o:
            sys.exit("pc relative: " + name)
    w("    { " + ", ".join("0x%08x" % x for x in ws) + " },   // " + name + ": " + "; ".join("%s %s" % x for x in ins))
    asm_blocks.append((name, ins))
w("};")
w("u64 hook_resume[NHOOKS];")
w("volatile u32 hook_calls[NHOOKS];")
w("u64 hook_arg[NHOOKS][2];")
w("static const u64 SEED_ADDR = 0x%xUL; static const u32 SEED_PRE = 0x%08x, SEED_BL = 0x%08x, SEED_POST = 0x%08x;" % SEED)
lines = [".text", ".p2align 2"]
for i, (name, ins) in enumerate(asm_blocks):
    lines.append(".globl _thunk_%d\n_thunk_%d:" % (i, i))
    lines.append("  adrp x16, _hook_arg@PAGE\n  add x16, x16, _hook_arg@PAGEOFF+%d\n  stp x0, x1, [x16]" % (i * 16))
    lines.append("  adrp x16, _hook_calls@PAGE\n  add x16, x16, _hook_calls@PAGEOFF+%d\n  mov w17, #1\n  stadd w17, [x16]" % (i * 4))
    for m, o in ins:
        lines.append("  %s %s" % (m, o))
    lines.append("  adrp x16, _hook_resume@PAGE\n  ldr x16, [x16, _hook_resume@PAGEOFF+%d]\n  br x16" % (i * 8))
w("__asm__(" + "\n    ".join('"%s\\n"' % l.replace("\n", "\\n") for l in lines) + ");")
for i in range(n):
    w("extern void thunk_%d(void);" % i)
w("static void* const THUNK[NHOOKS] = { " + ", ".join("(void*)&thunk_%d" % i for i in range(n)) + " };")
w(open("probe3_tail.c").read())
print("\n".join(out))
